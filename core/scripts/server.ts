import fetch from '@vue-storefront/core/lib/fetch/server';

import { serverHooksExecutors } from '@vue-storefront/core/server/hooks'
import { cacheInstanceFactory } from './utils/cache-instance';
import { createCacheInvalidationHandler, createOutputCache } from './utils/output-cache';
import { createRenderResponseHandler, createSsrErrorHandler, renderSsrResponse, lookupSsrResponse } from './utils/ssr-response';

const gracefulShutdown = require('http-graceful-shutdown')
const qs = require('qs')
const config = require('config')
const path = require('path')
const glob = require('glob')
const fs = require('fs')
const rootPath = require('app-root-path').path
const resolve = file => path.resolve(rootPath, file)
const serverExtensions = glob.sync('src/modules/*/server.{ts,js}')
const configProviders: Function[] = []

const PM2_INSTANCE_ID = process.env.NODE_APP_INSTANCE || process.env.pm_id || process.env.PM2_INSTANCE_ID;
const PM2_PROCESS_NAME = process.env.name || process.env.PM2_PROCESS_NAME;

function getProcessLogPrefix () {
  const parts: string[] = [`pid:${process.pid}`];

  if (PM2_INSTANCE_ID !== undefined && PM2_INSTANCE_ID !== null && `${PM2_INSTANCE_ID}`.length > 0) {
    parts.push(`pm2:${PM2_INSTANCE_ID}`);
  }

  if (PM2_PROCESS_NAME) {
    parts.push(`name:${PM2_PROCESS_NAME}`);
  }

  return `[${parts.join(' ')}]`;
}

serverExtensions.map(serverModule => {
  const module = require(resolve(serverModule))
  if (module.configProvider && typeof module.configProvider === 'function') {
    configProviders.push(module.configProvider)
  }
})

serverHooksExecutors.afterProcessStarted(config.server)
const express = require('express')
const ms = require('ms')
const helmet = require('helmet')

const cache = cacheInstanceFactory();
const apiStatus = require('./utils/api-status')
const HTMLContent = require('../pages/Compilation')
const ssr = require('./utils/ssr-renderer')

const compileOptions = {
  escape: /{{([^{][\s\S]+?[^}])}}/g,
  interpolate: /{{{([\s\S]+?)}}}/g
}
const NOT_ALLOWED_SSR_EXTENSIONS_REGEX = new RegExp(`^.*\\.(${config.server.ssrDisabledFor.extensions.join('|')})$`)

const isProd = process.env.NODE_ENV === 'production'

const app = express()

serverHooksExecutors.afterApplicationInitialized({ app, config: config.server, isProd })

const templatesCache = ssr.initTemplatesCache(config, compileOptions)

let renderer

if (isProd) {
  // In production: create server renderer using server bundle and index HTML
  // template from real fs.
  // The server bundle is generated by vue-ssr-webpack-plugin.
  const clientManifest = require(resolve('dist/client/vue-ssr-client-manifest.json'))
  const bundle = require(resolve('dist/server/vue-ssr-server-bundle.json'))
  // src/index.template.html is processed by html-webpack-plugin to inject
  // build assets and output as dist/client/index.html.
  // TODO: Add dynamic templates loading from (config based?) list
  renderer = ssr.createRenderer(bundle, clientManifest)
} else {
  // In development: setup the dev server with watch and hot-reload,
  // and create a new renderer on bundle / index template update.
  require(resolve('core/build/dev-server'))(app, (bundle, template) => {
    templatesCache['default'] = ssr.compileTemplate(template, compileOptions) // Important Notice: template switching doesn't work with dev server because of the HMR
    renderer = ssr.createRenderer(bundle)
  })
}

function healthCheck (req, res) {
  res.status(200).end();
}

function forwardCacheInvalidation (url: string): void {
  fetch(url)
    .then(response => response.text())
    .then(body => {
      if (!body) return

      try {
        if (JSON.parse(body).code !== 200) console.log(body)
      } catch (error) {
        console.error('Invalid Cache Invalidation response format', error)
      }
    })
    .catch(error => console.error(error))
}

const invalidateCache = createCacheInvalidationHandler({
  config, cache, apiStatus,
  beforeInvalidated: serverHooksExecutors.beforeCacheInvalidated,
  afterInvalidated: serverHooksExecutors.afterCacheInvalidated,
  forwardInvalidation: forwardCacheInvalidation
})

const serve = (path, cache, options?) => express.static(resolve(path), Object.assign({
  fallthrough: false,
  setHeaders: cache && isProd ? function (res, path) {
    const mimeType = express.static.mime.lookup(path);
    let maxAge = config.expireHeaders.default;
    if (config.expireHeaders.hasOwnProperty(mimeType)) {
      maxAge = config.expireHeaders.get(mimeType);
    }
    res.setHeader('Cache-Control', 'public, max-age=' + ms(maxAge) / 1000);
  } : null
}, options))

const themeRoot = require('../build/theme-path')

if (config.server.helmet && config.server.helmet.enabled && isProd) {
  app.use(helmet(config.server.helmet.config))
}

app.use('/dist', serve('dist/client', true))
app.use('/assets', serve(themeRoot + '/assets', true))
app.use('/service-worker.js', serve('dist/client/service-worker.js', false, {
  setHeaders: function (res, path, stat) {
    res.set('Content-Type', 'text/javascript; charset=UTF-8')
  }
}))

app.post('/invalidate', invalidateCache)
app.get('/invalidate', invalidateCache)
app.get('/healthcheck', healthCheck)

function cacheVersion (req, res) {
  res.send(fs.readFileSync(resolve('core/build/cache-version.json')))
}

app.get('/cache-version.json', cacheVersion)

let globalContextConfig: any = null;

app.get('*', async (req, res, next) => {
  if (NOT_ALLOWED_SSR_EXTENSIONS_REGEX.test(req.path)) {
    apiStatus(res, 'Vue Storefront: Resource is not found', 404)
    return
  }

  const s = Date.now()
  const errorHandler = createSsrErrorHandler({
    res, req, logger: console,
    isResourceNotFound: () => NOT_ALLOWED_SSR_EXTENSIONS_REGEX.test(req.path),
    apiStatus,
    onException: err => serverHooksExecutors.ssrException({ err, req, isProd })
  })
  const logFinalFailure = error => console.error('SSR request failed:', req.url, error)

  if (!req.path.endsWith('/')) {
    const hasQuery = Object.values(req.query).length;
    let redirectUrl = `${req.path}/`;

    if (hasQuery) {
      redirectUrl += '?' + qs.stringify(req.query);
    }

    return res.redirect(301, redirectUrl);
  }

  const dynamicCacheHandler = (requestConfig) => {
    const outputCache = createOutputCache({ cache, config: requestConfig, logger: console })
    const cacheRequest = outputCache.createRequest(
      req.get('x-vs-store-code') || 'main',
      `${req.protocol}://${req.get('host')}${req.originalUrl}`,
      req.headers.cookie
    )
    const dynamicRequestHandler = () => {
      if (!renderer) {
        res.setHeader('Content-Type', 'text/html')
        res.status(202).end(HTMLContent)
        return next()
      }
      const context = ssr.initSSRRequestContext(app, req, res, requestConfig, cacheRequest.cleanUrl)
      const renderHandler = createRenderResponseHandler({
        req, res, context, outputCache, cacheRequest,
        tagging: requestConfig.server.useOutputCacheTagging,
        logger: console,
        beforeOutput: output => serverHooksExecutors.beforeOutputRenderedResponse({ req, res, context, output, isProd }),
        afterOutput: output => serverHooksExecutors.afterOutputRenderedResponse({ req, res, context, output, isProd }),
        processOutput: output => ssr.applyAdvancedOutputProcessing(context, output, templatesCache, isProd),
        onComplete: () => {
          console.log(`${getProcessLogPrefix()} whole request [${req.url}]: ${Date.now() - s}ms`)
          next()
        }
      })
      return renderSsrResponse({
        render: () => renderer.renderToString(context),
        renderHandler, errorHandler,
        cleanup: () => ssr.clearContext(context),
        logFinalFailure
      })
    }
    return lookupSsrResponse({
      read: () => outputCache.read(cacheRequest),
      cacheRequest,
      onMiss: dynamicRequestHandler,
      logCache: result => {
        const message = result === 'miss'
          ? `cache miss [${req.url}], request: ${Date.now() - s}ms`
          : `${result === 'redirect' ? 'redirect ' : ''}cache hit [${req.url}], cached request: ${Date.now() - s}ms`
        console.log(`${getProcessLogPrefix()} ${message}`)
      },
      res, onHit: next, errorHandler, logFinalFailure
    })
  }

  let requestContextConfig: any = config.util.extendDeep({}, config);

  if (config.server.dynamicConfigReload && !globalContextConfig) {
    if (configProviders.length > 0) {
      const configPromises = [];
      configProviders.forEach(configProvider => {
        if (typeof configProvider === 'function') {
          configPromises.push(configProvider(req).then(loadedConfig => {
            requestContextConfig = config.util.extendDeep(requestContextConfig, loadedConfig)
          }).catch(() => {
            if (!config.server.dynamicConfigContinueOnError) {
              if (req.url !== '/error') {
                res.redirect('/error')
              }
            }
          }))
        }
      })
      await Promise.all(configPromises)

      if (!config.server.dynamicConfigReloadWithEachRequest) {
        globalContextConfig = config.util.extendDeep({}, requestContextConfig)
      }
    }
  } else if (globalContextConfig) {
    requestContextConfig = config.util.extendDeep({}, globalContextConfig)
  }

  return dynamicCacheHandler(requestContextConfig)
})

let port = process.env.PORT || config.server.port
const host = process.env.HOST || config.server.host
let keepAliveTimeout = process.env.KEEP_ALIVE_TIMEOUT || config.server.keepAliveTimeout
keepAliveTimeout = parseInt(keepAliveTimeout) || 5000
const start = () => {
  const server = app.listen(port, host);
  server.keepAliveTimeout = keepAliveTimeout;
  server.headersTimeout = keepAliveTimeout + 1000;
  gracefulShutdown(server, {
    onShutdown: async () => {
      if (cache) await cache.close();
    }
  });

  server.on('listening', () => {
    console.log(`\n\n----------------------------------------------------------`)
    console.log('|                                                        |')
    console.log(`| Vue Storefront Server started at http://${host}:${port} |`)
    console.log(`| Worker ${getProcessLogPrefix()}                                         |`)
    console.log('|                                                        |')
    console.log(`----------------------------------------------------------\n\n`)

    serverHooksExecutors.httpServerIsReady({ server, config: config.server, isProd })

    if (process && typeof process.send === 'function') {
      process.send('ready');
    }
  }).on('error', (e: any) => {
    if (e.code === 'EADDRINUSE') {
      port = parseInt(port) + 1
      console.log(`The port is already in use, trying ${port}`)
      start()
    }
  })
}
start()
